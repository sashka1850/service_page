import { readFile, writeFile } from 'node:fs/promises';
import { validateContent, renderSite, renderData, renderPrivacy } from './content.mjs';
const root = new URL('../', import.meta.url);
const content = validateContent(JSON.parse(await readFile(new URL('content/site.json', root), 'utf8')));
const dataSource = renderData(content);
await writeFile(new URL('src/data.js', root), dataSource);
await writeFile(new URL('index.html', root), renderSite(content, await readFile(new URL('index.template.html', root), 'utf8')));
await writeFile(new URL('privacy.html', root), renderPrivacy(content, await readFile(new URL('privacy.template.html', root), 'utf8')));
const data = dataSource.replace(/^export /gm, '');
const repair = (await readFile(new URL('src/repair.js', root), 'utf8')).replace(/^export /gm, '');
const app = repair + '\n' + (await readFile(new URL('src/app.js', root), 'utf8')).replace(/^import .*?;\s*/gm, '');
await writeFile(new URL('src/site.js', root), '// Generated by npm run build. Edit data.js and app.js instead.\n(() => {\n"use strict";\n' + data + '\n' + app + '\n})();\n');
console.log('Built src/site.js — supports file:// and HTTP.');
