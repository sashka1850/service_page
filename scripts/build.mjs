import { readFile, writeFile } from 'node:fs/promises';
import { services, team } from '../src/data.js';
import { renderServices, renderTeam } from './render-content.mjs';
const root = new URL('../', import.meta.url);
const data = (await readFile(new URL('src/data.js', root), 'utf8')).replace(/^export /gm, '');
const repair = (await readFile(new URL('src/repair.js', root), 'utf8')).replace(/^export /gm, '');
const app = repair + '\n' + (await readFile(new URL('src/app.js', root), 'utf8')).replace(/^import .*?;\s*/gm, '');
await writeFile(new URL('src/site.js', root), '// Generated by npm run build. Edit data.js and app.js instead.\n(() => {\n"use strict";\n' + data + '\n' + app + '\n})();\n');
console.log('Built src/site.js — supports file:// and HTTP.');

const indexPath = new URL('index.html', root);
let html = await readFile(indexPath, 'utf8');
function replaceBlock(name, content) {
  const start = '<!-- build:' + name + ' -->';
  const end = '<!-- /build:' + name + ' -->';
  const from = html.indexOf(start);
  const to = html.indexOf(end, from);
  if (from === -1 || to === -1) throw new Error('Missing HTML build markers: ' + name);
  html = html.slice(0, from + start.length) + '\n        ' + content + '\n        ' + html.slice(to);
}
replaceBlock('services', renderServices(services));
replaceBlock('team', renderTeam(team));
await writeFile(indexPath, html);
